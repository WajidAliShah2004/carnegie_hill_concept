import {defineField, defineType} from 'sanity'
import {HomeIcon} from '@sanity/icons/Home'

/**
 * The shop's details. One document, never more than one.
 * Feeds the front page, the Visit section, the footer, the Contact page,
 * the search engine data, and llms.txt.
 */
export const businessInfo = defineType({
  name: 'businessInfo',
  title: 'Business info',
  type: 'document',
  icon: HomeIcon,
  groups: [
    {name: 'identity', title: 'Name', default: true},
    {name: 'address', title: 'Address'},
    {name: 'contact', title: 'Contact'},
    {name: 'hours', title: 'Hours'},
    {name: 'links', title: 'Links'},
    {name: 'images', title: 'Pictures'},
    {name: 'unverified', title: 'Not verified yet'},
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Business name',
      type: 'string',
      group: 'identity',
      validation: (Rule) => Rule.required().error('Add the business name.'),
    }),
    defineField({
      name: 'alternateName',
      title: 'Other name the shop uses',
      type: 'string',
      group: 'identity',
      description: 'The shorter name on the logo, if it is different.',
    }),
    defineField({
      name: 'street',
      title: 'Street address',
      type: 'string',
      group: 'address',
      validation: (Rule) => Rule.required().error('Add the street address.'),
    }),
    defineField({
      name: 'crossStreets',
      title: 'Cross streets',
      type: 'string',
      group: 'address',
      description: 'For example: between 90th and 91st St.',
    }),
    defineField({
      name: 'city',
      title: 'City',
      type: 'string',
      group: 'address',
      validation: (Rule) => Rule.required().error('Add the city.'),
    }),
    defineField({
      name: 'region',
      title: 'State',
      type: 'string',
      group: 'address',
      validation: (Rule) => Rule.required().error('Add the state.'),
    }),
    defineField({
      name: 'postcode',
      title: 'Zip code',
      type: 'string',
      group: 'address',
      validation: (Rule) => Rule.required().error('Add the zip code.'),
    }),
    defineField({
      name: 'country',
      title: 'Country',
      type: 'string',
      group: 'address',
      description: 'Two letters, for example US.',
      validation: (Rule) => Rule.required().error('Add the country.'),
    }),
    defineField({
      name: 'phone',
      title: 'Phone number',
      type: 'string',
      group: 'contact',
      description: 'The number a phone can dial, for example +12128312224.',
      validation: (Rule) => Rule.required().error('Add the phone number.'),
    }),
    defineField({
      name: 'phoneDisplay',
      title: 'Phone number as it is written on the site',
      type: 'string',
      group: 'contact',
      description: 'For example 212-831-2224.',
      validation: (Rule) => Rule.required().error('Add the phone number as it should be written.'),
    }),
    defineField({
      name: 'email',
      title: 'Public email address',
      type: 'string',
      group: 'contact',
      validation: (Rule) => Rule.required().email().error('Add the public email address.'),
    }),
    defineField({
      name: 'hours',
      title: 'Opening hours',
      type: 'array',
      group: 'hours',
      of: [{type: 'openingHours'}],
      description: 'Only the days the shop keeps regular hours.',
      validation: (Rule) => Rule.required().min(1).error('Add at least one row of hours.'),
    }),
    defineField({
      name: 'sundayNote',
      title: 'What the site says about Sunday',
      type: 'sourcedLine',
      group: 'hours',
      description: 'Sunday is not in the hours list above. Whatever goes here has to be sourced.',
    }),
    defineField({
      name: 'appointmentNote',
      title: 'What the site says about appointments',
      type: 'sourcedLine',
      group: 'hours',
    }),
    defineField({
      name: 'directionsUrl',
      title: 'Directions link',
      type: 'url',
      group: 'links',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'googleReviewsUrl',
      title: 'Link to the reviews on Google',
      type: 'url',
      group: 'links',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'googleWriteReviewUrl',
      title: 'Link for writing a Google review',
      type: 'url',
      group: 'links',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'yelpUrl',
      title: 'Link to the Yelp page',
      type: 'url',
      group: 'links',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'socialLinks',
      title: 'Social profiles',
      type: 'array',
      group: 'links',
      of: [{type: 'socialLink'}],
      description: 'A profile that is not ticked as confirmed does not appear on the site.',
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      type: 'image',
      group: 'images',
      options: {hotspot: false},
      // A warning, not an error: the facts can be published before the original
      // arrives. The production site build refuses to run without it.
      validation: (Rule) =>
        Rule.required().warning('Add the logo. The live site cannot be built without it.'),
    }),
    defineField({
      name: 'storefrontImage',
      title: 'Photo of the shop front',
      type: 'image',
      group: 'images',
      options: {hotspot: true},
      validation: (Rule) =>
        Rule.required().warning(
          'Add the shop front photo. The live site cannot be built without it.',
        ),
    }),
    defineField({
      name: 'shareImage',
      title: 'Picture used when the site is shared',
      type: 'image',
      group: 'images',
      options: {hotspot: true},
    }),
    defineField({
      name: 'geo',
      title: 'Map position',
      type: 'geopoint',
      group: 'unverified',
      description: 'Leave empty until the position has been checked against the real shop front.',
    }),
    defineField({
      name: 'foundingYear',
      title: 'Year the shop started',
      type: 'number',
      group: 'unverified',
      description: 'Leave empty until the owner confirms the year.',
      validation: (Rule) => Rule.integer().min(1800).max(2100),
    }),
  ],
  preview: {
    select: {title: 'name', subtitle: 'street'},
  },
})
